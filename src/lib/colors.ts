// Helper function to get color value
export const getThemeColor = (colorName: string, shade: number = 500): string => {
  const colorKey = colorName as keyof typeof materialColorPalette;
  if (materialColorPalette[colorKey]) {
    return materialColorPalette[colorKey][shade as keyof typeof materialColorPalette[typeof colorKey]] || materialColorPalette[colorKey][500];
  }
  // Fallback for sky color
  if (colorName === 'sky') {
    const skyColors = {
      50: '#f0f9ff',
      100: '#e0f2fe',
      200: '#bae6fd',
      300: '#7dd3fc',
      400: '#38bdf8',
      500: '#0ea5e9',
      600: '#0284c7',
      700: '#0369a1',
      800: '#075985',
      900: '#0c4a6e'
    };
    return skyColors[shade as keyof typeof skyColors] || skyColors[500];
  }
  return materialColorPalette.blue[500]; // Default fallback
}; 